class FullExportTests(TestCase):
    """A real export with most options on: one site, every column described, no stray file."""

    def setUp(self) -> None:
        label = make_label("Org", color="#FF0000")
        channels = [make_channel(telegram_id=i, label=label, title=f"C{i}") for i in range(1, 5)]
        day = datetime.datetime(2024, 3, 1, tzinfo=datetime.UTC)
        n = 1
        for i, a in enumerate(channels):
            for b in channels[i + 1 :]:
                Message.objects.create(
                    telegram_id=n, channel=a, date=day + datetime.timedelta(days=n), forwarded_from=b
                )
                n += 1

    def test_export_is_one_site_with_every_column_described(self) -> None:
        tmpdir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, tmpdir)
        with override_settings(BASE_DIR=Path(tmpdir)):
            os.symlink(Path(__file__).resolve().parent.parent / "webapp_engine", Path(tmpdir) / "webapp_engine")
            call_command(
                "structural_analysis",
                "--graph-2d",
                "--html",
                "--xlsx",
                "--csv",
                "--dominance",
                "--links",
                "--community-strategies",
                "LEIDEN",
                "--measures",
                "PAGERANK,AMPLIFICATION",
                "--timeline-step",
                "year",
                name="site",
                stdout=io.StringIO(),
                stderr=io.StringIO(),
            )
        root = os.path.join(tmpdir, "exports", "site")
        names = set(os.listdir(root))
        self.assertTrue({"index.html", "methods.html", "data.html", "DATA.md", "graph.html"} <= names)
        self.assertFalse({"config.json", "start.sh", "graph3d.html"} & names)
        with open(os.path.join(root, "channel_table.html"), encoding="utf-8") as f:
            page = f.read()
        self.assertIn("export-contents-menu", page)
        self.assertIn('href="channel_table.xlsx"', page)  # the page's own downloads
        self.assertNotIn("<!-- pulpit:sitenav --><!-- /pulpit:sitenav -->", page)  # the marker was filled
        undescribed = []
        for name in sorted(names):
            if data_dictionary.has_columns(root, name):
                for sheet, headers in data_dictionary.columns_of(root, name):
                    undescribed += [
                        (name, sheet, h) for h in headers if not data_dictionary.describe_column(h, name, sheet)
                    ]
        self.assertEqual(undescribed, [])
        wb = openpyxl.load_workbook(os.path.join(root, "channel_table.xlsx"))
        self.assertEqual(wb.sheetnames[0], "About")
        with open(os.path.join(root, "nodes.csv"), encoding="utf-8") as f:
            self.assertTrue(f.readline().startswith("channel_id,channel,url,label,"))
        # Every channel carries its environment depth (0 in target): the column is never left empty.
        with open(os.path.join(root, "nodes.csv"), encoding="utf-8", newline="") as f:
            self.assertEqual({row["environment_depth"] for row in csv.DictReader(f)}, {"0"})
        # The study header states the days the analysed messages span, not a calendar period.
        with open(os.path.join(root, "summary.json"), encoding="utf-8") as f:
            summary = json.load(f)
        self.assertEqual((summary["first_message"], summary["last_message"]), ("2024-03-02", "2024-03-07"))
        with open(os.path.join(root, "index.html"), encoding="utf-8") as f:
            landing = f.read()
        self.assertIn("2024-03-02 – 2024-03-07", landing)
        self.assertIn('id="periods"', landing)
        # The map's summary links only to tables that exist; every local link of every page resolves.
        for name in sorted(n for n in names if n.endswith(".html")):
            with open(os.path.join(root, name), encoding="utf-8") as f:
                for target in re.findall(r'href="([^"#?:]+\.(?:html|xlsx|csv|md|json))["#?]', f.read()):
                    self.assertIn(target, names, f"{name} links to {target}")

    def test_compare_refuses_an_export_of_an_earlier_layout(self) -> None:
        tmpdir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, tmpdir)
        old_export = os.path.join(tmpdir, "exports", "old")
        os.makedirs(old_export)
        with open(os.path.join(old_export, "index.html"), "w", encoding="utf-8") as f:
            f.write("<html><body>an earlier landing page</body></html>")
        with override_settings(BASE_DIR=Path(tmpdir)), self.assertRaisesMessage(CommandError, "earlier version"):
            call_command("compare_analysis", old_export, target="old", stdout=io.StringIO())


class StudyPeriodTests(SimpleTestCase):
    """The period an export states is the requested bounds or the analysed messages' own span."""

    def _inventory(self, summary: dict, timeline: dict | None = None) -> site.Inventory:
        return site.Inventory(root="", names=[], summary=summary, timeline=timeline or {})

    def test_requested_bounds_win(self) -> None:
        summary = {
            "options": {"startdate": "2024-07-01", "enddate": "2026-06-30"},
            "first_message": "2024-07-03",
            "last_message": "2026-06-11",
        }
        self.assertEqual(publication.analysed_range(summary), ("2024-07-01", "2026-06-30"))

    def test_an_open_side_is_the_messages_own_day_never_a_period_edge(self) -> None:
        summary = {"options": {}, "first_message": "2019-05-27", "last_message": "2026-11-27"}
        timeline = {"periods": [{"key": "2020", "start": "2020-01-01", "end": "2020-12-31"}]}
        self.assertEqual(site._period_label(self._inventory(summary, timeline)), "2019-05-27 – 2026-11-27")

    def test_an_export_without_the_record_says_so(self) -> None:
        self.assertEqual(site._period_label(self._inventory({"options": {}})), "all stored messages")


