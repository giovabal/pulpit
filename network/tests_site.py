        self.assertEqual(pages.compared_name("channel_table.xlsx"), "channel_table_2.xlsx")
        self.assertEqual(pages.original_name("graph3d_2.html"), "graph3d.html")
        self.assertIsNone(pages.original_name("graph.html"))
