class TableSheetTests(SimpleTestCase):
    def _reload(self, wb: object) -> object:
        buffer = io.BytesIO()
        wb.save(buffer)
        buffer.seek(0)
        return openpyxl.load_workbook(buffer)

    def test_text_is_never_a_formula_and_yes_no_is_a_number(self) -> None:
        wb = tables._new_workbook("Demo")
        tables._table_sheet(wb, "Channels", ["Channel", "Mutual"], [("", [["=1+1", True], ["Alpha", False]])])
        ws = self._reload(wb)["Channels"]
        self.assertEqual(ws["A2"].value, "=1+1")
        self.assertEqual(ws["A2"].data_type, "s")
        self.assertEqual([ws["B2"].value, ws["B3"].value], [1, 0])

    def test_a_table_too_long_for_a_sheet_continues_on_the_next(self) -> None:
        wb = tables._new_workbook("Demo")
        with mock.patch.object(tables, "EXCEL_MAX_ROWS", 4):
            tables._table_sheet(wb, "Curves", ["n"], [("", [[i] for i in range(7)])])
        self.assertEqual(wb.sheetnames, ["Curves", "Curves (2)", "Curves (3)"])
        self.assertEqual([c.value for c in wb["Curves (2)"]["A"]], ["n", 3, 4, 5])

    def test_sheet_titles_stay_unique_and_within_the_limit(self) -> None:
        wb = tables._new_workbook("Demo")
