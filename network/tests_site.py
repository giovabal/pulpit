class CsvCellTests(SimpleTestCase):
    """No text cell of an export's CSV can be run as a formula by the spreadsheet that opens it."""

    def test_formula_like_text_is_guarded_and_numbers_are_not(self) -> None:
        from network.utils import csv_value

        for text in ("=1+1", "+cmd|' /C calc'!A0", "-2+3+cmd", "@SUM(1,1)", "\t=1", "-"):
            self.assertEqual(csv_value(text), "'" + text)
        for value in ("-0.25", "+18", "Alpha", "a=b", "2024-01-01", "", -3, 0.5):
            self.assertEqual(csv_value(value), value)
        self.assertEqual(csv_value("'=1+1"), "'=1+1")  # never guarded twice
        self.assertEqual([csv_value(True), csv_value(False), csv_value(None)], [1, 0, ""])

    def test_every_writer_goes_through_the_guard(self) -> None:
        from network.utils import csv_writer

        buffer = io.StringIO()
        writer = csv_writer(buffer)
        writer.writerow(["channel_id", "channel"])
        writer.writerows([[1, '=HYPERLINK("x")'], [2, None]])
        self.assertEqual(buffer.getvalue().splitlines(), ["channel_id,channel", '1,"\'=HYPERLINK(""x"")"', "2,"])

    def test_the_export_files_use_it(self) -> None:
        from network import dyads, exporter

        for module in (exporter, dyads):
            with open(module.__file__, encoding="utf-8") as f:
                self.assertNotIn("csv.writer(", f.read(), module.__name__)
